"""Structural contract for problem adapters used by the shared task executor."""
from typing import Protocol, Any
from pathlib import Path


class ProblemAdapter(Protocol):
    ROOT: Path
    entrypoint: str
    CandidateError: type[Exception]

    def check_run(self, directory: Path) -> dict: ...
    def members(self, directory: Path) -> list: ...
    def checked_candidate(self, value: dict) -> Any: ...
    def parse_candidate(self, text: str, config: dict) -> Any: ...
    def build_prompt(self, config: dict, task: dict, parents: list, members: list) -> str: ...
    def evaluate(self, directory: Path, state: dict, protocol: dict, candidate: Any) -> tuple[dict, bool]: ...
    def validate_result(self, result: dict, instances: list) -> None: ...
    def client_config(self, protocol: dict) -> Any: ...
    def transport(self, protocol: dict) -> Any: ...
    def summary(self, directory: Path, *, write_files: bool = False) -> dict: ...
